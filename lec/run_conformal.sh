#!/usr/bin/env bash
# =============================================================================
# Cadence Conformal LEC Execution Wrapper
# Flow Stage: [3/5] CONFORMAL Logic Equivalence Checking
# =============================================================================

set -e

PRJ_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PRJ_ROOT"

mkdir -p lec

echo "======================================================================="
echo " [CADENCE CONFORMAL] Starting Logic Equivalence Checking (LEC)"
echo " Project root : $PRJ_ROOT"
echo " Comparing    : Golden RTL vs. Synthesized Gate Netlist"
echo "======================================================================="

# -----------------------------------------------------------------------------
# 1. Locate technology library
# -----------------------------------------------------------------------------
LIB=""
for l in \
    "/home/cadence/install/FOUNDRY/digital/90nm/dig/lib/typical.lib" \
    "/home/cadence/install/FOUNDRY/digital/90nm/dig/lib/gsclib090_typical.lib" \
    "$PRJ_ROOT/typical.lib" \
    "$PRJ_ROOT/syn/typical.lib"; do
    if [ -f "$l" ]; then
        LIB="$l"
        break
    fi
done

if [ -z "$LIB" ]; then
    echo "[WARNING] typical.lib not found. Using default Conformal library path."
    LIB="/home/cadence/install/FOUNDRY/digital/90nm/dig/lib/typical.lib"
fi
echo "[INFO] Using standard cell library: $LIB"

# -----------------------------------------------------------------------------
# 2. Locate synthesized netlist
# -----------------------------------------------------------------------------
NETLIST="$PRJ_ROOT/syn/netlists/bharatvoice_top_netlist.v"
if [ ! -f "$NETLIST" ]; then
    echo "[ERROR] Synthesized netlist not found at: $NETLIST"
    exit 1
fi
echo "[INFO] Using netlist: $NETLIST"

# -----------------------------------------------------------------------------
# 3. Build full-path RTL file list
# -----------------------------------------------------------------------------
RTL_FILES=""
for f in ibex_core.sv boot_rom.sv uart_rx.sv irq_ctrl.sv clint.sv \
         crc_checker.sv transaction_guard.sv power_manager.sv payment_engine.sv \
         audio_engine.sv sram_model.sv sram_controller.sv spi_master.sv \
         spi_controller.sv transaction_cache.sv bus_interconnect.sv bharatvoice_top.sv; do
    RTL_FILES="$RTL_FILES $PRJ_ROOT/$f"
done

RPT="$PRJ_ROOT/lec/lec_verification.rpt"

# -----------------------------------------------------------------------------
# 4. Generate runtime dofile with absolute paths (avoids cwd issues)
# -----------------------------------------------------------------------------
DOFILE="$PRJ_ROOT/lec/conformal_lec_runtime.do"
cat > "$DOFILE" << DOEOF
// Generated by run_conformal.sh — uses absolute paths
read library -statename typical $LIB -both
read design -golden -sv $RTL_FILES
set root module bharatvoice_top -golden
read design -revised -verilog $NETLIST
set root module bharatvoice_top -revised
set system mode lec
add compared points -all
compare
report compare data -class nonequivalent -class abort -class notcompared
report verification -verbose > $RPT
exit -force
DOEOF

echo "[INFO] Runtime dofile written to: $DOFILE"

# -----------------------------------------------------------------------------
# 5. Try to find lec binary; try common Cadence install prefixes
# -----------------------------------------------------------------------------
LEC_BIN=$(command -v lec 2>/dev/null || true)
for p in \
    "/home/cadence/install/lec/bin/lec" \
    "/opt/cadence/CONFRML*/bin/lec" \
    "/opt/cadence/lec*/bin/lec"; do
    if [ -z "$LEC_BIN" ]; then
        LEC_BIN=$(ls $p 2>/dev/null | head -1 || true)
    fi
done

if [ -z "$LEC_BIN" ]; then
    echo "[ERROR] 'lec' binary not found. Conformal LEC may not be installed or not in PATH."
    echo "[INFO]  Skipping Conformal LEC and continuing to next stage (Tempus STA)."
    echo "CONFORMAL_SKIPPED=true" > "$PRJ_ROOT/lec/lec_skipped.flag"
    exit 0   # exit 0 so the pipeline continues
fi

echo "[INFO] Using lec binary: $LEC_BIN"

# -----------------------------------------------------------------------------
# 6. Run Conformal LEC in batch mode
# -----------------------------------------------------------------------------
"$LEC_BIN" -nogui -dofile "$DOFILE" -logfile "$PRJ_ROOT/lec/conformal.log"

echo "======================================================================="
echo " [CADENCE CONFORMAL] LEC Verification Complete!"
echo " Report: $RPT"
echo "======================================================================="
